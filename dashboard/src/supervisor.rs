
use crate::db;
use sqlx::PgPool;
use std::path::Path;

/// Path of the companion-overrides env file. Production sets this via
/// COMPANION_OVERRIDES_PATH=/var/lib/fetchproxies/companion-overrides.env;
/// dev/preview.sh points it under /tmp so no root is needed.
fn companion_overrides_path() -> String {
    std::env::var("COMPANION_OVERRIDES_PATH")
        .unwrap_or_else(|_| "/var/lib/fetchproxies/companion-overrides.env".into())
}
fn nitter_bridge_env_path() -> String {
    std::env::var("NITTER_BRIDGE_ENV_PATH")
        .unwrap_or_else(|_| "/var/lib/fetchproxies/nitter-bridge.env".into())
}

/// Render every supervised file from current DB state. Idempotent —
/// safe to call from any handler, even when nothing changed; the path
/// unit's `PathChanged` only fires on byte-level diffs.
pub async fn regenerate_all(pool: &PgPool) {
    if let Err(e) = render_companion(pool).await {
        tracing::warn!("supervisor: companion render failed: {e:?}");
    }
    if let Err(e) = render_nitter_bridge(pool).await {
        tracing::warn!("supervisor: nitter bridge render failed: {e:?}");
    }
}

async fn render_companion(pool: &PgPool) -> std::io::Result<()> {
    let egress = db::get_egress_mode(pool, "companion")
        .await
        .ok()
        .flatten()
        .map(|e| e.mode)
        .unwrap_or_else(|| "proxy_chain".to_string());
    let auth = db::get_youtube_auth(pool).await.ok().flatten();

    let mut lines = vec![
        "# Generated by fetchproxies-dashboard. DO NOT EDIT.".to_string(),
        "# Source of truth: youtube_companion_auth + service_egress_mode in postgres.".to_string(),
    ];

    match egress.as_str() {
        "direct" => lines.push("PROXY=".to_string()),
        _ => lines.push("PROXY=http://127.0.0.1:1184".to_string()),
    }

    match auth.as_ref().map(|a| a.auth_method.as_str()) {
        Some("oauth") => {
            lines.push("YOUTUBE_SESSION_OAUTH_ENABLED=true".to_string());
            lines.push("YOUTUBE_SESSION_COOKIES=".to_string());
            lines.push("JOBS_YOUTUBE_SESSION_PO_TOKEN_ENABLED=false".to_string());
        }
        Some("cookies") => {
            lines.push("YOUTUBE_SESSION_OAUTH_ENABLED=false".to_string());
            let raw = auth.as_ref().and_then(|a| a.cookies.as_deref()).unwrap_or("");
            lines.push(format!("YOUTUBE_SESSION_COOKIES={}", shell_quote(raw)));
            lines.push("JOBS_YOUTUBE_SESSION_PO_TOKEN_ENABLED=false".to_string());
        }
        _ => {
            lines.push("YOUTUBE_SESSION_OAUTH_ENABLED=false".to_string());
            lines.push("YOUTUBE_SESSION_COOKIES=".to_string());
            lines.push("JOBS_YOUTUBE_SESSION_PO_TOKEN_ENABLED=true".to_string());
        }
    }

    let body = lines.join("\n") + "\n";
    write_atomic(&companion_overrides_path(), &body).await
}

async fn render_nitter_bridge(pool: &PgPool) -> std::io::Result<()> {
    let egress = db::get_egress_mode(pool, "nitter")
        .await
        .ok()
        .flatten()
        .map(|e| e.mode)
        .unwrap_or_else(|| "proxy_chain".to_string());

    let forwarder = match egress.as_str() {
        "direct" => "",
        _ => "socks5://127.0.0.1:1081",
    };

    let body = format!(
        "# Generated by fetchproxies-dashboard. DO NOT EDIT.\n\
         # FORWARDER controls whether nitter-http-bridge chains via the\n\
         # proxy-chain socks5 listener (proxy_chain) or speaks plain HTTP\n\
         # CONNECT through the VM's gateway (direct).\n\
         FORWARDER={forwarder}\n"
    );
    write_atomic(&nitter_bridge_env_path(), &body).await
}

async fn write_atomic(path: &str, body: &str) -> std::io::Result<()> {
    let p = Path::new(path);
    if let Some(parent) = p.parent() {
        tokio::fs::create_dir_all(parent).await?;
    }
    let tmp = p.with_extension("env.tmp");
    tokio::fs::write(&tmp, body).await?;
    tokio::fs::rename(&tmp, p).await?;
    Ok(())
}

/// Single-quote the value for use in a systemd EnvironmentFile line.
/// systemd's env-file parser supports `KEY="value"` and `KEY='value'`
/// with the same quoting rules as shell single-quotes — single-quote
/// the whole thing and escape internal single quotes by closing,
/// inserting `\'`, reopening.
fn shell_quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for c in s.chars() {
        if c == '\'' {
            out.push_str("'\\''");
        } else {
            out.push(c);
        }
    }
    out.push('\'');
    out
}
